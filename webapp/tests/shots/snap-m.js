const { chromium } = require('playwright-core');
(async () => {
  const browser = await chromium.launch({ args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
  const m = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  await m.goto('http://127.0.0.1:8080/?static=1', { waitUntil: 'networkidle' });
  await m.waitForTimeout(600);
  await m.screenshot({ path: 'm0-hero.png' });
  await m.click('#btnDemo');
  await m.waitForFunction(() => !document.querySelector('#checkBody').hidden, { timeout: 30000 });
  await m.waitForTimeout(900);
  await m.evaluate(() => { document.documentElement.style.scrollBehavior='auto'; document.getElementById('sec-check').scrollIntoView({block:'start'}); });
  await m.waitForTimeout(400);
  await m.screenshot({ path: 'm1-check.png' });
  await m.evaluate(() => { const el=document.querySelector('.metric-grid'); if(el) el.scrollIntoView({block:'center'}); });
  await m.waitForTimeout(350);
  await m.screenshot({ path: 'm2-metrics.png' });
  await m.click('#btnProcess');
  await m.waitForFunction(() => document.querySelector('#btnProcess').textContent.includes('重新精修') || document.querySelector('#btnProcess').textContent.includes('失败'), { timeout: 30000 });
  await m.waitForTimeout(600);
  await m.evaluate(() => { const el=document.querySelector('.eq-layout'); if(el) el.scrollIntoView({block:'center'}); });
  await m.waitForTimeout(400);
  await m.screenshot({ path: 'm3-eq.png' });
  await m.click('#btnRender');
  await m.waitForFunction(() => document.querySelector('#btnRender').textContent.includes('重新渲染') || document.querySelector('#btnRender').textContent.includes('失败'), { timeout: 30000 });
  await m.waitForTimeout(700);
  await m.evaluate(() => { document.getElementById('sec-create').scrollIntoView({block:'start'}); });
  await m.waitForTimeout(400);
  await m.screenshot({ path: 'm4-create.png' });
  await m.click('#btnRecheck');
  await m.waitForTimeout(1000);
  await m.evaluate(() => { const el=document.querySelector('.tree'); if(el) el.scrollIntoView({block:'center'}); });
  await m.waitForTimeout(400);
  await m.screenshot({ path: 'm5-tree.png' });
  console.log('ok');
  await browser.close();
})();
